CREATE TABLE sign_in_attempt (
    email        VARCHAR(254) PRIMARY KEY,
    failed_count INTEGER      NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ
);
--rollback DROP TABLE sign_in_attempt;
