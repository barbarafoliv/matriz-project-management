-- Application tables. See docs/database.md.

--changeset matriz:001-app-user
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL
);
-- An email can only be used by one account, ignoring case (EC-01).
CREATE UNIQUE INDEX app_user_email_uk ON app_user (LOWER(email));
--rollback DROP TABLE app_user;

--changeset matriz:001-project
CREATE TABLE project (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT project_name_ck CHECK (CHAR_LENGTH(BTRIM(name)) >= 3)
);
--rollback DROP TABLE project;

--changeset matriz:001-project-member
CREATE TABLE project_member (
    project_id BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role       VARCHAR(20) NOT NULL,
    PRIMARY KEY (project_id, user_id),
    CONSTRAINT project_member_role_ck CHECK (role IN ('PROJECT_MANAGER', 'MEMBER'))
);
CREATE INDEX project_member_user_ix ON project_member (user_id);
-- At most one project manager per project.
CREATE UNIQUE INDEX project_member_one_pm_uk ON project_member (project_id) WHERE role = 'PROJECT_MANAGER';
--rollback DROP TABLE project_member;

--changeset matriz:001-task
CREATE TABLE task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    title       VARCHAR(150)  NOT NULL,
    description VARCHAR(2000),
    due_date    DATE,
    priority    VARCHAR(10)   NOT NULL DEFAULT 'MEDIUM',
    status      VARCHAR(20)   NOT NULL DEFAULT 'TODO',
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT task_title_ck CHECK (CHAR_LENGTH(BTRIM(title)) >= 3),
    CONSTRAINT task_priority_ck CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT task_status_ck CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE'))
);
CREATE INDEX task_project_ix ON task (project_id);
--rollback DROP TABLE task;

--changeset matriz:001-task-assignee
-- The primary key prevents assigning the same user twice (EC-08).
-- That the user is a project member is checked by the application (EC-09).
CREATE TABLE task_assignee (
    task_id    BIGINT      NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (task_id, user_id)
);
CREATE INDEX task_assignee_user_ix ON task_assignee (user_id);
--rollback DROP TABLE task_assignee;

--changeset matriz:001-comment
-- author_id becomes null when the author's account is deleted (US-09).
CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT        NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    author_id  BIGINT        REFERENCES app_user (id) ON DELETE SET NULL,
    content    VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT comment_content_ck CHECK (CHAR_LENGTH(BTRIM(content)) >= 1)
);
CREATE INDEX comment_task_ix ON comment (task_id);
--rollback DROP TABLE comment;

